'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const dir=path.resolve(__dirname,'../dist');
const read=name=>fs.readFileSync(path.join(dir,name),'utf8');
const app=read('app.js'),css=read('styles.css'),html=read('index.html'),boot=read('app-bootstrap.js');
assert.match(app,/class="example-card noun-summary-card"/,'specific card for noun summary');
assert.match(app,/class="noun-article-label">أداة الاسم/,'visible Arabic label');
assert.match(app,/class="noun-article-value" lang="de" dir="ltr"/,'article badge uses readable LTR');
assert.match(app,/word\.article \? articleHtml\(word\.article\)/,'actual der/die/das shown from word');
assert.match(app,/class="noun-plural-line"/,'plural row still visible');
assert.match(app,/nounCaseReference\(word\)/,'case declension table unaffected');
assert.match(css,/#word-dialog \.word-content \.noun-summary-card\{[^}]*background:#142f43/,'card always contrasts against light page');
assert.match(css,/#word-dialog \.noun-article-label\{[^}]*color:#f0f7ff!important/,'label cannot turn dark on dark');
assert.match(css,/#word-dialog \.noun-article-value\{[^}]*background:#edf6ff/,'article has a light badge');
for(const article of ['der','die','das'])assert.match(css,new RegExp('#word-dialog \\.noun-article-value \\[data-article="'+article+'"\\]'),'colored '+article+' remains distinct');
const build=boot.match(/const SCRIPT_BUILD = '([^']+)'/)?.[1];
assert.ok(build&&html.includes('styles.css?v='+build)&&html.includes('app-bootstrap.js?v='+build));
assert.ok(boot.includes('app.js?v='+build));
console.log('PASS: noun article label and der/die/das are legible in both themes and declension persists.');
