'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const app=fs.readFileSync(path.join(root,'dist/app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'dist/buttons-gradient-plus.css'),'utf8');
const start=app.indexOf('function exampleHtml(example) {');
const end=app.indexOf('function renderInlineVerb(word) {',start);
assert.ok(start>=0&&end>start,'example card renderer exists');
const snippet=app.slice(start,end);
assert.match(snippet,/class="icon-button reference-example-audio"/,'example uses an icon button');
assert.match(snippet,/type="button"/,'icon button is not a form submit');
assert.match(snippet,/data-example-speak="\$\{esc\(example.de\)\}"/,'spoken text remains tied to example');
assert.match(snippet,/aria-label="استمع إلى المثال"/,'icon retains screen reader name');
assert.match(snippet,/\$\{SPEAKER_ICON\}/,'same speaker SVG as the word heading');
assert.doesNotMatch(snippet,/>استمع إلى المثال ♬</,'old visible text is removed');
assert.match(app,/if \(example\) speak\(example\.dataset\.exampleSpeak, example\);/,'same click handler is retained');
assert.match(css,/button\.reference-example-audio\s*\{[^}]*width:44px;[^}]*height:44px;[^}]*border-radius:50% !important;/s,'circular 44px touch target');
assert.match(css,/button\.reference-example-audio svg\s*\{[^}]*width:22px;[^}]*height:22px;/s,'SVG matches word audio size');
console.log('PASS: example speaker is icon-only, accessible, round and still calls speech.');
